<?php

// The only places SQL differs between MySQL and Postgres. Everything else in
// db.php is written in the subset both accept.

function db_driver() {
  return DB_DRIVER;
}

function db_quote_identifier($identifier) {
  if (!preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $identifier)) {
    throw new InvalidArgumentException("Invalid SQL identifier '$identifier'");
  }
  return db_driver() === 'pgsql' ? '"' . $identifier . '"' : '`' . $identifier . '`';
}

/**
 * Insert a row, or update $update_cols if one with the same $key_cols exists.
 *
 * $values is a map of column => value and must contain every key and update
 * column. $key_cols must match a primary key or unique index.
 */
function db_upsert($table, $key_cols, $update_cols, $values) {
  global $pdo;

  $columns = array_keys($values);
  $quoted_columns = implode(', ', array_map('db_quote_identifier', $columns));
  $placeholders = implode(', ', array_fill(0, count($columns), '?'));
  $sql = "INSERT INTO " . db_quote_identifier($table) . " ($quoted_columns) VALUES ($placeholders)";

  if (db_driver() === 'pgsql') {
    $quoted_keys = implode(', ', array_map('db_quote_identifier', $key_cols));
    if ($update_cols) {
      $assignments = implode(', ', array_map(function ($col) {
        $quoted = db_quote_identifier($col);
        return "$quoted = EXCLUDED.$quoted";
      }, $update_cols));
      $sql .= " ON CONFLICT ($quoted_keys) DO UPDATE SET $assignments";
    } else {
      $sql .= " ON CONFLICT ($quoted_keys) DO NOTHING";
    }
  } else {
    if ($update_cols) {
      $assignments = implode(', ', array_map(function ($col) {
        $quoted = db_quote_identifier($col);
        return "$quoted = VALUES($quoted)";
      }, $update_cols));
    } else {
      // A self-assignment, since ON DUPLICATE KEY UPDATE needs at least one
      $quoted = db_quote_identifier($key_cols[0]);
      $assignments = "$quoted = $quoted";
    }
    $sql .= " ON DUPLICATE KEY UPDATE $assignments";
  }

  $stmt = $pdo->prepare($sql);
  $stmt->execute(array_values($values));
}

/**
 * Insert a row unless one conflicting with a primary key or unique index
 * already exists. Returns whether a row was inserted.
 *
 * $values is a map of column => value.
 */
function db_insert_ignore($table, $values) {
  global $pdo;

  $columns = array_keys($values);
  $quoted_columns = implode(', ', array_map('db_quote_identifier', $columns));
  $placeholders = implode(', ', array_fill(0, count($columns), '?'));
  $quoted_table = db_quote_identifier($table);

  if (db_driver() === 'pgsql') {
    $sql = "INSERT INTO $quoted_table ($quoted_columns) VALUES ($placeholders) ON CONFLICT DO NOTHING";
  } else {
    $sql = "INSERT IGNORE INTO $quoted_table ($quoted_columns) VALUES ($placeholders)";
  }

  $stmt = $pdo->prepare($sql);
  $stmt->execute(array_values($values));
  return $stmt->rowCount() > 0;
}

/**
 * The id generated by the last insert on this connection. Postgres needs the
 * name of the sequence, which phinx names <table>_<column>_seq.
 */
function db_last_insert_id($sequence = null) {
  global $pdo;

  if (db_driver() === 'pgsql') {
    return (int) $pdo->lastInsertId($sequence);
  }
  return (int) $pdo->lastInsertId();
}
